// Generates the calculator and blog registries from the folder structure, so adding a
// calculator only means adding calculators/<slug>/config.ts + content.mdx (+ test).
// Runs automatically before dev, build and test.
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const root = path.resolve(import.meta.dirname, '..');
const calcDir = path.join(root, 'calculators');
const blogDir = path.join(root, 'content', 'blog');
const HEADER = '// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit.\n';

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return;
  fs.writeFileSync(file, text);
}

// ---- calculators ----
const slugs = fs
  .readdirSync(calcDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_') && fs.existsSync(path.join(calcDir, d.name, 'config.ts')))
  .map((d) => d.name)
  .sort();

let server = HEADER + "import type { CalculatorEntry } from '@/lib/registry-types';\n";
slugs.forEach((s, i) => {
  server += `import c${i} from './${s}/config';\n`;
  if (fs.existsSync(path.join(calcDir, s, 'content.mdx'))) server += `import * as m${i} from './${s}/content.mdx';\n`;
});
server += '\nexport const CALCULATOR_ENTRIES: CalculatorEntry[] = [\n';
slugs.forEach((s, i) => {
  const hasContent = fs.existsSync(path.join(calcDir, s, 'content.mdx'));
  server += `  { config: c${i}, content: ${hasContent ? `m${i} as unknown as CalculatorEntry['content']` : 'null'} },\n`;
});
server += '];\n';
writeIfChanged(path.join(calcDir, '_registry.generated.ts'), server);

let loaders = HEADER + "import type { CalculatorConfig } from '@/lib/engine/types';\n\n";
loaders += 'export const CALCULATOR_LOADERS: Record<string, () => Promise<{ default: CalculatorConfig }>> = {\n';
for (const s of slugs) loaders += `  '${s}': () => import('./${s}/config'),\n`;
loaders += '};\n';
writeIfChanged(path.join(calcDir, '_loaders.generated.ts'), loaders);

// ---- blog ----
fs.mkdirSync(blogDir, { recursive: true });
const posts = fs
  .readdirSync(blogDir)
  .filter((f) => f.endsWith('.mdx'))
  .map((f) => {
    const { data } = matter(fs.readFileSync(path.join(blogDir, f), 'utf8'));
    const slug = f.replace(/\.mdx$/, '');
    for (const key of ['title', 'description', 'date', 'updated', 'category', 'calculator', 'keyword']) {
      if (!data[key]) throw new Error(`content/blog/${f}: missing frontmatter "${key}"`);
    }
    const iso = (d) => (d instanceof Date ? d.toISOString().slice(0, 10) : String(d));
    return { slug, ...data, date: iso(data.date), updated: iso(data.updated) };
  })
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));

let blog = HEADER + "import type { PostMeta } from '@/lib/registry-types';\n\n";
blog += `export const POSTS: PostMeta[] = ${JSON.stringify(posts, null, 2)};\n\n`;
blog += 'export const POST_LOADERS: Record<string, () => Promise<{ default: import("mdx/types").MDXContent }>> = {\n';
for (const p of posts) blog += `  '${p.slug}': () => import('./${p.slug}.mdx'),\n`;
blog += '};\n';
writeIfChanged(path.join(blogDir, '_posts.generated.ts'), blog);

console.log(`registry: ${slugs.length} calculators, ${posts.length} posts`);
